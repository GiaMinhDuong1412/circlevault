def serve(pid: str, text: str) -> PlainTextResponse:
    """XUnity gửi từng câu đang hiện trong game. Trả bản dịch (đã có / dịch ngay), đồng thời lưu câu mới vào dự án."""
    g = _gametr()
    text = text or ""
    if not text.strip():
        return PlainTextResponse(text)
    with g._lock:
        p = g._load(pid)
        idx = {it["t"]: i for i, it in enumerate(p["items"])}
        i = idx.get(text)
        if i is not None:
            vi = p["items"][i].get("vi")
            if vi and not p["items"][i].get("bad"):
                return PlainTextResponse(vi)
        else:
            p["items"].append({"t": text, "kind": "ui" if len(text) < 30 and " " not in text.strip() else "say",
                               "ctx": "Khi chơi", "who": "", "vi": None})
            i = len(p["items"]) - 1
            p["seen_at"] = time.time()
            g._save(p)
    s = translate.settings()
    if s.get("engine") == "claude":          # mỗi câu một lượt Claude thì chậm và tốn: khi chơi dùng Google, Claude dịch lại sau
        s = {**s, "engine": "google"}
    s = {**s, "source": g.TR_LANG.get(p.get("lang") or "en", "auto")}
    try:
        vi = translate.translate_texts([text], s, kind="gamefile")[0]
    except translate.TranslateError as e:
        raise HTTPException(503, str(e))
    if vi:
        with g._lock:
            p = g._load(pid)
            for it in p["items"]:
                if it["t"] == text and it.get("vi") is None:
                    it["vi"] = vi
                    break
            g._save(p)
    return PlainTextResponse(vi or text)
