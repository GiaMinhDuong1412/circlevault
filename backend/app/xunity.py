"""Việt hóa game Unity khi chơi bằng XUnity.AutoTranslator (công cụ mã nguồn mở cộng đồng hay dùng nhất cho game Unity).

Dùng khi chữ của game không nằm trong file đọc được (viết thẳng trong mã game, game IL2CPP…):
  1. Cài BepInEx (trình nạp mod) + XUnity.AutoTranslator vào thư mục game – tải bản mới nhất từ GitHub của hai dự án.
     Game Mono → BepInEx 5; game IL2CPP (có GameAssembly.dll) → BepInEx 6 bản IL2CPP. Nhớ danh sách file đã thêm để gỡ sạch.
  2. Cấu hình XUnity: Language=vi, Endpoint=CustomTranslate, Url = CircleVault (`GET /api/translate/games/<id>/xunity?from&to&text`).
     Khi chơi, mỗi câu hiện trên màn hình được gửi về CircleVault: lưu vào dự án (để sửa / gửi Claude chat dịch), trả bản dịch
     đã có, chưa có thì dịch ngay bằng bộ dịch đang chọn (Google mặc định, nhớ trong bộ nhớ dịch).
  3. Áp dụng = ghi `BepInEx/Translation/vi/Text/zz_CircleVault.txt` (định dạng XUnity: gốc=dịch, thoát \\n \\= \\\\) và sửa
     các câu tương ứng trong `_AutoGeneratedTranslations.txt` – bản dịch của Claude / sửa tay thay bản máy dịch.
Không dùng cho game online có chống gian lận.
"""
