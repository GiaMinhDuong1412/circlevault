# ------------------------------------------------------------------ nhận dạng game
def detect(root: Path) -> dict | None:
    data = [d for d in root.iterdir() if d.is_dir() and d.name.endswith("_Data")] if root.is_dir() else []
    if not data:
        return None
    il2cpp = (root / "GameAssembly.dll").is_file() or (data[0] / "il2cpp_data").is_dir()
    arch = "x64"
    for exe in [root / "UnityPlayer.dll", *root.glob("*.exe")]:
        try:
            with open(exe, "rb") as f:
                head = f.read(4096)
            pe = int.from_bytes(head[0x3C:0x40], "little")
            machine = int.from_bytes(head[pe + 4:pe + 6], "little")
            if head[:2] == b"MZ" and machine in (0x14C, 0x8664):
                arch = "x86" if machine == 0x14C else "x64"
                break
        except (OSError, ValueError):
            continue
    plug = root / "BepInEx" / "plugins"
    return {"il2cpp": il2cpp, "arch": arch, "bepinex": (root / "BepInEx" / "core").is_dir(),
            "xunity": plug.is_dir() and any(plug.rglob("XUnity.AutoTranslator.Plugin.Core.dll")),
            "data": data[0].name}


# ------------------------------------------------------------------ tải từ GitHub
def _get(url: str, timeout: int = 60) -> bytes:
    req = urllib.request.Request(url, headers=UA)
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return r.read()
    except OSError as e:
        raise HTTPException(502, f"Không tải được từ GitHub ({e}). Kiểm tra mạng rồi thử lại.")


def _asset(repo: str, pattern: str) -> tuple[str, str]:
    """(tên, link tải) của file đầu tiên khớp mẫu, tìm trong các bản phát hành mới nhất (kể cả bản thử)."""
    rels = json.loads(_get(f"https://api.github.com/repos/{repo}/releases?per_page=30"))
    rx = re.compile(pattern, re.I)
    for rel in rels:
        for a in rel.get("assets") or []:
            if rx.fullmatch(a.get("name") or ""):
                return a["name"], a["browser_download_url"]
    raise HTTPException(502, f"Không tìm thấy bản tải phù hợp trên GitHub {repo}.")


def _extract(blob: bytes, root: Path, skip_existing: bool) -> list[str]:
    added = []
    with zipfile.ZipFile(io.BytesIO(blob)) as z:
        for info in z.infolist():
            name = info.filename.replace("\\", "/")
            if info.is_dir() or name.startswith("/") or ".." in name.split("/"):
                continue
            dest = root / name
            if dest.exists() and skip_existing:
                continue
            dest.parent.mkdir(parents=True, exist_ok=True)
            with z.open(info) as src, open(dest, "wb") as out:
                shutil.copyfileobj(src, out)
            added.append(name)
    return added


def _state_path(root: Path) -> Path:
    import hashlib
    return STATE / (hashlib.sha1(str(root.resolve()).lower().encode()).hexdigest()[:16] + ".json")


def install(root: Path, pid: str, src_lang: str) -> dict:
    info = detect(root)
    if not info:
        raise HTTPException(400, "Đây không phải thư mục game Unity (không thấy thư mục <Tên game>_Data).")
    added: list[str] = []
    if not info["bepinex"]:
        if info["il2cpp"]:
            name, url = _asset("BepInEx/BepInEx", rf"BepInEx-Unity\.IL2CPP-win-{info['arch']}-6[\w.\-+]*\.zip")
        else:
            name, url = _asset("BepInEx/BepInEx", rf"BepInEx_(?:win_)?{info['arch']}_5\.[\d.]+\.zip")
        added += _extract(_get(url, 300), root, skip_existing=True)
    if not info["xunity"]:
        pat = r"XUnity\.AutoTranslator-BepInEx-IL2CPP-[\d.]+\.zip" if info["il2cpp"] else r"XUnity\.AutoTranslator-BepInEx-[\d.]+\.zip"
        name, url = _asset("bbepis/XUnity.AutoTranslator", pat)
        added += _extract(_get(url, 300), root, skip_existing=True)
    write_config(root, pid, src_lang)
    st = {"root": str(root), "added": added, "at": time.time(), "pid": pid, **detect(root)}
    STATE.mkdir(parents=True, exist_ok=True)
    old = _state_path(root)
    if old.is_file():
        prev = json.loads(old.read_text(encoding="utf-8"))
        st["added"] = sorted(set(prev.get("added", [])) | set(added))
    old.write_text(json.dumps(st, ensure_ascii=False), encoding="utf-8")
    return st


def _ini_set(text: str, section: str, key: str, value: str) -> str:
    lines = text.splitlines()
    sec_i = next((i for i, ln in enumerate(lines) if ln.strip().lower() == f"[{section.lower()}]"), None)
    if sec_i is None:
        return text.rstrip("\n") + f"\n\n[{section}]\n{key}={value}\n"
    end = next((i for i in range(sec_i + 1, len(lines)) if lines[i].strip().startswith("[")), len(lines))
    for i in range(sec_i + 1, end):
        if lines[i].split("=", 1)[0].strip().lower() == key.lower():
            lines[i] = f"{key}={value}"
            return "\n".join(lines) + "\n"
    lines.insert(end, f"{key}={value}")
    return "\n".join(lines) + "\n"


def write_config(root: Path, pid: str, src_lang: str) -> None:
    import os
    port = int(os.environ.get("CIRCLEVAULT_PORT") or config.load().get("port") or 8686)
    ini = root / "BepInEx" / "config" / "AutoTranslatorConfig.ini"
    ini.parent.mkdir(parents=True, exist_ok=True)
    text = ini.read_text(encoding="utf-8-sig", errors="replace") if ini.is_file() else ""
    for sec, k, v in [("General", "Language", "vi"), ("General", "FromLanguage", {"zh": "zh-CN"}.get(src_lang, src_lang or "en")),
                      ("Service", "Endpoint", "CustomTranslate"), ("Service", "FallbackEndpoint", ""),
                      ("Custom", "Url", f"http://127.0.0.1:{port}/api/translate/games/{pid}/xunity"),
                      ("Custom", "EnableShortDelay", "True"), ("Custom", "DisableSpamChecks", "True"),
                      ("Behaviour", "MaxCharactersPerTranslation", "1000")]:
        text = _ini_set(text, sec, k, v)
    ini.write_text(text, encoding="utf-8")


def uninstall(root: Path) -> int:
    """Xóa đúng các file CircleVault đã thêm (BepInEx/XUnity tải về) + file bản dịch; mod khác của người dùng giữ nguyên."""
    sp = _state_path(root)
    n = 0
    names = json.loads(sp.read_text(encoding="utf-8")).get("added", []) if sp.is_file() else []
    for name in names + [f"BepInEx/Translation/vi/Text/{TR_FILE}"]:
        f = root / name
        if f.is_file():
            try:
                f.unlink()
                n += 1
            except OSError:
                pass
    for d in sorted({(root / x).parent for x in names}, key=lambda p: -len(p.parts)):
        try:
            if d != root and d.is_dir() and not any(d.iterdir()):
                d.rmdir()
        except OSError:
            pass
    sp.unlink(missing_ok=True)
    return n


# ------------------------------------------------------------------ định dạng file dịch của XUnity
def enc(s: str) -> str:
    s = s.replace("\\", "\\\\").replace("=", "\\=").replace("\r", "\\r").replace("\n", "\\n")
    return s.replace("//", "\\/\\/")


def dec_line(line: str) -> tuple[str, str] | None:
    parts, cur, esc = [], [], False
    for ch in line:
        if esc:
            cur.append({"n": "\n", "r": "\r"}.get(ch, ch))
            esc = False
        elif ch == "\\":
            esc = True
        elif ch == "=" and not parts:
            parts.append("".join(cur))
            cur = []
        else:
            cur.append(ch)
    if not parts:
        return None
    parts.append("".join(cur))
    return parts[0], parts[1]


def apply(root: Path, final: list[dict]) -> dict:
    d = root / "BepInEx" / "Translation" / "vi" / "Text"
    d.mkdir(parents=True, exist_ok=True)
    tr = {it["t"]: it["final"] for it in final if it.get("final") and it["final"] != it["t"]}
    body = "// Ban dich cua CircleVault (sua trong app roi bam Ap dung). Xoa file nay de bo.\n" + \
           "".join(f"{enc(k)}={enc(v)}\n" for k, v in tr.items())
    (d / TR_FILE).write_text(body, encoding="utf-8")
    auto = d / "_AutoGeneratedTranslations.txt"
    fixed = 0
    if auto.is_file():
        out = []
        for ln in auto.read_text(encoding="utf-8", errors="replace").splitlines():
            kv = dec_line(ln) if ln and not ln.startswith("//") else None
            if kv and kv[0] in tr:
                if kv[1] != tr[kv[0]]:
                    fixed += 1
                out.append(f"{enc(kv[0])}={enc(tr[kv[0]])}")
            else:
                out.append(ln)
        auto.write_text("\n".join(out) + "\n", encoding="utf-8")
    return {"texts": len(tr), "files": 1 + (1 if fixed else 0)}


def restore(root: Path) -> int:
    f = root / "BepInEx" / "Translation" / "vi" / "Text" / TR_FILE
    if f.is_file():
        f.unlink()
        return 1
    return 0


